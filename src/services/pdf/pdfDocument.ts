import type { Content, TableCell, TDocumentDefinitions } from "pdfmake/interfaces";

import { formatDateTime } from "../../utils/format";

/**
 * Shared layout for the PDF reports: a title block, sections with tables and
 * figures, and "Page x of y" footers. Builders return plain document
 * definitions, so their content can be checked without rendering a PDF.
 */

const COLORS = {
  text: "#0F172A",
  muted: "#64748B",
  rule: "#E2E8F0",
  stripe: "#F8FAFC",
  bar: "#10B981",
  track: "#E2E8F0",
};

export interface ReportOptions {
  /** Title Case, as on the page the report comes from. */
  title: string;
  /** Who and what the report covers, e.g. the organization and the view. */
  subtitle?: string;
  /** One line per filter or range, e.g. "1 Oct 2026 to 19 Oct 2026". */
  details: string[];
  /** A statement every reader needs, e.g. that spend counts reimbursed expenses only. */
  note?: string;
  generatedBy: string;
  generatedAt?: Date;
  content: Content[];
}

export function buildReport({ title, subtitle, details, note, generatedBy, generatedAt = new Date(), content }: ReportOptions): TDocumentDefinitions {
  const generated = `Generated by ${generatedBy} on ${formatDateTime(generatedAt.toISOString())}`;
  return {
    info: { title, creator: "Ledgerly" },
    pageSize: "A4",
    pageMargins: [40, 40, 40, 56],
    defaultStyle: { font: "Roboto", fontSize: 9, color: COLORS.text, lineHeight: 1.2 },
    styles: {
      title: { fontSize: 18, bold: true, margin: [0, 0, 0, 2] },
      subtitle: { fontSize: 11, color: COLORS.muted, margin: [0, 0, 0, 6] },
      detail: { color: COLORS.muted },
      note: { italics: true, margin: [0, 6, 0, 0] },
      section: { fontSize: 12, bold: true, margin: [0, 16, 0, 6] },
      tableHeader: { bold: true, color: COLORS.muted, fontSize: 8 },
      figureLabel: { fontSize: 8, color: COLORS.muted },
      figureValue: { fontSize: 13, bold: true },
      notice: { color: COLORS.muted, margin: [0, 4, 0, 0] },
    },
    footer: (currentPage, pageCount) => ({
      columns: [
        { text: `${title} · ${generated}`, width: "*" },
        { text: `Page ${currentPage} of ${pageCount}`, width: "auto", alignment: "right" },
      ],
      margin: [40, 20, 40, 0],
      fontSize: 8,
      color: COLORS.muted,
    }),
    content: [
      { text: title, style: "title" },
      ...(subtitle ? [{ text: subtitle, style: "subtitle" }] : []),
      ...details.map((detail) => ({ text: detail, style: "detail" })),
      ...(note ? [{ text: note, style: "note" }] : []),
      { canvas: [{ type: "line", x1: 0, y1: 8, x2: 515, y2: 8, lineWidth: 0.5, lineColor: COLORS.rule }] },
      ...content,
    ],
  };
}

/** A sentence-case section heading followed by its content. */
export function section(title: string, ...body: Content[]): Content {
  return { stack: [{ text: title, style: "section" }, ...body] };
}

/** A line of muted text, e.g. an explanation or an empty state. */
export const notice = (text: string): Content => ({ text, style: "notice" });

/** Headline figures side by side, e.g. total spend and expense count. */
export function figures(items: Array<{ label: string; value: string; detail?: string }>): Content {
  return {
    columns: items.map(({ label, value, detail }) => ({
      width: "*",
      stack: [
        { text: label, style: "figureLabel" },
        { text: value, style: "figureValue" },
        ...(detail ? [{ text: detail, style: "detail", fontSize: 8 }] : []),
      ],
    })),
    columnGap: 12,
    margin: [0, 12, 0, 0],
  };
}

export interface TableColumn {
  header: string;
  /** Amounts and counts align right. */
  align?: "left" | "right";
  width?: number | "*" | "auto";
}

/** A table whose header row repeats on every page, with an optional total row. */
export function table(columns: TableColumn[], rows: TableCell[][], totalRow?: string[]): Content {
  const alignment = (index: number) => columns[index].align ?? "left";
  return {
    table: {
      headerRows: 1,
      widths: columns.map((column) => column.width ?? "auto"),
      body: [
        columns.map((column, index) => ({ text: column.header, style: "tableHeader", alignment: alignment(index) })),
        ...rows.map((row) => row.map((cell, index) => (typeof cell === "string" ? { text: cell, alignment: alignment(index) } : cell))),
        ...(totalRow ? [totalRow.map((text, index) => ({ text, bold: true, alignment: alignment(index) }))] : []),
      ],
    },
    layout: {
      hLineWidth: (index) => (index === 1 ? 0.75 : 0.5),
      vLineWidth: () => 0,
      hLineColor: () => COLORS.rule,
      fillColor: (rowIndex) => (rowIndex > 0 && rowIndex % 2 === 0 ? COLORS.stripe : null),
      paddingTop: () => 4,
      paddingBottom: () => 4,
    },
  };
}

/** A share of a total as a percentage with a small bar; the figure is always written out. */
export function shareCell(share: number): TableCell {
  const width = 60;
  const filled = Math.max(0, Math.min(1, share)) * width;
  return {
    columns: [
      {
        width,
        canvas: [
          { type: "rect", x: 0, y: 3, w: width, h: 5, r: 2, color: COLORS.track },
          ...(filled > 0 ? [{ type: "rect" as const, x: 0, y: 3, w: filled, h: 5, r: 2, color: COLORS.bar }] : []),
        ],
      },
      { text: `${Math.round(share * 100)}%`, width: "auto", margin: [6, 0, 0, 0] },
    ],
  };
}
