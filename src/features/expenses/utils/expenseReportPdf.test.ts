import { describe, expect, it } from "vitest";

import { pdfTables, pdfText } from "../../../test/pdfText";
import type { Expense } from "../types/expense";
import { buildExpenseReport, describeExpenseFilters, type ExpenseReportInput } from "./expenseReportPdf";
import { initialExpenseFilters } from "../types/expense";

function expense(overrides: Partial<Expense>): Expense {
  return {
    id: crypto.randomUUID(),
    organizationId: "org-1",
    departmentId: "dept-engineering",
    teamId: "team-engineering",
    employeeId: "user-1",
    employeeName: "Esha Employee",
    type: "MEALS",
    title: "Client lunch",
    amount: 1_000,
    currency: "INR",
    description: "Lunch",
    expenseDate: "2026-10-01",
    status: "submitted",
    documentIds: [],
    createdAt: "2026-10-01T10:00:00.000Z",
    updatedAt: "2026-10-01T10:00:00.000Z",
    ...overrides,
  };
}

const input = (overrides: Partial<ExpenseReportInput> = {}): ExpenseReportInput => ({
  expenses: [
    expense({ title: "Taxi to airport", type: "TRANSPORTATION", amount: 850, status: "reimbursed", expenseDate: "2026-10-12" }),
    expense({ title: "Hotel in Pune", type: "ACCOMMODATION", amount: 12_400.5, status: "approved", expenseDate: "2026-10-03" }),
  ],
  matching: 2,
  viewLabel: "My Expenses",
  filters: ["Status: Approved"],
  showEmployee: false,
  organizationName: "Acme Corp",
  generatedBy: "Esha Employee",
  generatedAt: new Date("2026-10-19T10:00:00"),
  ...overrides,
});

describe("buildExpenseReport", () => {
  it("lists every expense with its date, type, status and amount, and totals them", () => {
    const report = buildExpenseReport(input());

    const [expenses] = pdfTables(report);
    expect(expenses[0]).toEqual(["Date", "Title", "Expense type", "Status", "Amount"]);
    expect(expenses.slice(1)).toEqual([
      ["12 Oct 2026", "Taxi to airport", "Transportation", "Reimbursed", "₹850"],
      ["3 Oct 2026", "Hotel in Pune", "Accommodation", "Approved", "₹12,400.50"],
      ["Total", "", "", "", "₹13,250.50"],
    ]);
  });

  it("names the view, the filters and who created it, and says what counts as spend", () => {
    const text = pdfText(buildExpenseReport(input()));

    expect(text).toContain("Expense Report");
    expect(text).toContain("Acme Corp · My Expenses");
    expect(text).toContain("Status: Approved");
    expect(text).toContain("Spend includes reimbursed expenses only; the total covers every listed expense. Amounts are in rupees.");
    expect(text).toMatch(/Reimbursed \(spend\)\n₹850\n1 expense/);
  });

  it("puts the page number and the author in every footer", () => {
    const { footer } = buildExpenseReport(input());

    const text = pdfText({ content: (footer as (page: number, pages: number) => never)(2, 3) });
    expect(text).toContain("Page 2 of 3");
    expect(text).toContain("Generated by Esha Employee on 19 Oct 2026, 10:00 am");
  });

  it("names the employee in wider views and what was paid in other currencies", () => {
    const report = buildExpenseReport(input({
      showEmployee: true,
      expenses: [
        expense({
          title: "Dinner in New York",
          employeeName: "Manu Manager",
          amount: 5_697.6,
          conversion: { originalAmount: 60, originalCurrency: "USD", rate: 94.96, rateDate: "2026-10-16", source: "ECB" },
        }),
        expense({ title: "Taxi", employeeName: "Rita Removed", employeeRemoved: true }),
      ],
    }));

    const [expenses] = pdfTables(report);
    expect(expenses[0]).toEqual(["Date", "Title", "Employee", "Expense type", "Status", "Amount", "Paid as"]);
    expect(expenses[1]).toEqual(["1 Oct 2026", "Dinner in New York", "Manu Manager", "Meals", "Submitted", "₹5,697.60", "USD 60.00"]);
    expect(expenses[2]).toContain("Rita Removed (removed)");
    expect(expenses[2].at(-1)).toBe("—");
  });

  it("says when the report stops short of every matching expense", () => {
    const text = pdfText(buildExpenseReport(input({ matching: 742 })));

    expect(text).toContain("This report lists the first 2 of 742 matching expenses. Narrow the filters to include the rest.");
  });

  it("explains an empty view", () => {
    const report = buildExpenseReport(input({ expenses: [], matching: 0, filters: [] }));

    expect(pdfTables(report)).toEqual([]);
    expect(pdfText(report)).toContain("No expenses match this view.");
    expect(pdfText(report)).toContain("All expenses in this view");
  });
});

describe("describeExpenseFilters", () => {
  it("describes each filter in use", () => {
    expect(describeExpenseFilters({
      search: " taxi ",
      status: "reimbursed",
      type: "TRAVEL",
      dateFrom: "2026-10-01",
      dateTo: "2026-10-19",
    })).toEqual(["Dates: 1 Oct 2026 to 19 Oct 2026", "Status: Reimbursed", "Expense type: Travel", 'Search: "taxi"']);
    expect(describeExpenseFilters({ ...initialExpenseFilters, dateTo: "2026-10-19" })).toEqual(["Dates: until 19 Oct 2026"]);
    expect(describeExpenseFilters(initialExpenseFilters)).toEqual([]);
  });
});
